    def try_cases(
        self,
        cases: list[tuple[list[str], int]],
        fn: Callable[[list[list[int]], list[int]], int],
    ):
        for c in cases:
            self.osl.fill(c[0])
            res = fn(self.osl.K, self.osl.C)
            self.assertEqual(res, c[1])

